
#ifndef GRAMODS_GRAPHICS_NDIVIEW
#define GRAMODS_GRAPHICS_NDIVIEW

#include <gmGraphics/config.hh>

#ifdef gramods_ENABLE_NDI

// Required before gmCore/OFactory.hh for some compilers
#include <gmCore/io_size.hh>

#include <gmGraphics/View.hh>

BEGIN_NAMESPACE_GMGRAPHICS;

/**
   The NdiView is a view that publishes the graphics generated by its
   child views over network, Network Device Interface (NDI).

   The NdiView first calls its child views to render onto an RGBA
   buffer. Then this buffer is converted into a UYVY buffer, that is
   then sent over NDI with the specified NDI stream name and
   optionally also specified group.
*/
class NdiView
  : public View {

public:

  NdiView();

  /**
     Forwards rendering to the sub view and saves the result.
  */
  void renderFullPipeline(ViewSettings settings) override;

  /**
     Propagates the specified visitor.

     @see Object::Visitor
  */
  void traverse(Visitor *visitor) override;

  /**
     @see Object::initialize
  */
  void initialize() override;

  /**
     Sets the resolution to render and send at, regarless of
     resolution of the view itself. Default is to use the view
     resolution.

     \gmXmlTag{gmGraphics,NdiView,resolution}
  */
  void setResolution(gmCore::size2 res);

  /**
     Sets the NDI source name to use as identity.

     \gmXmlTag{gmGraphics,NdiView,name}
  */
  void setName(std::string name);

  /**
     Sets the NDI group name.

     \gmXmlTag{gmGraphics,NdiView,group}
  */
  void setGroup(std::string group);

  /**
     Set to true if to have the view show the UYVY compressed data
     instead of the original RGB data.

     \gmXmlTag{gmGraphics,NdiView,showUyvy}
  */
  void setShowUyvy(bool on);

  /**
     Sets the conversion matris to use for converting RGB color to
     YCrCb (YUV) to send over NDI. Per default BT601 is used for SD,
     Rec.709 for HD and Rec.2020 for UHD, as per the NDI
     documentation.

     \sa gramods::operator>>(std::istream &, Eigen::Matrix4f &)

     \gmXmlTag{gmGraphics,NdiView,yuvMatrix}
  */
  void setYuvMatrix(Eigen::Matrix4f M);

  /**
     Adds a view that should be saved to file.

     \gmXmlTag{gmGraphics,NdiView,view}
  */
  void addView(std::shared_ptr<View> view);

  GM_OFI_DECLARE;

private:

  struct Impl;
  std::unique_ptr<Impl> _impl;

};

END_NAMESPACE_GMGRAPHICS;

#endif
#endif
